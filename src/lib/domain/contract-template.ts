/** Modelo de cláusulas padrão (editável pelo proprietário antes da emissão). Não constitui assessoria jurídica. */
export function defaultClauses(orgName: string) {
  return `CLÁUSULA 1ª — OBJETO
A LOCADORA (${orgName}) cede ao LOCATÁRIO, a título de locação, o veículo identificado neste contrato, pelo período, modalidade e valores indicados no quadro-resumo.

CLÁUSULA 2ª — USO DO VEÍCULO
O LOCATÁRIO declara possuir habilitação válida e compatível, compromete-se a utilizar o veículo de forma diligente, respeitar a legislação de trânsito e não ceder a direção a terceiros não autorizados por escrito.

CLÁUSULA 3ª — PAGAMENTO
Os valores serão pagos conforme o cronograma de parcelas deste contrato. Atrasos poderão gerar encargos previstos em lei.

CLÁUSULA 4ª — VISTORIAS
Na retirada e na devolução, o LOCATÁRIO realizará vistoria com fotos pelo aplicativo MOVIX. Divergências serão analisadas pela LOCADORA.

CLÁUSULA 5ª — MULTAS, AVARIAS E OCORRÊNCIAS
Multas de trânsito e avarias ocorridas durante a locação são de responsabilidade do LOCATÁRIO, que deverá registrar qualquer ocorrência imediatamente no aplicativo.

CLÁUSULA 6ª — MANUTENÇÃO
Manutenções preventivas são de responsabilidade da LOCADORA. O LOCATÁRIO deve comunicar alertas no painel ou ruídos anormais.

CLÁUSULA 7ª — DEVOLUÇÃO
O veículo deverá ser devolvido na data final, nas mesmas condições de retirada, ressalvado o desgaste natural.

CLÁUSULA 8ª — ACEITE ELETRÔNICO
As partes reconhecem o aceite eletrônico registrado no MOVIX (identidade, data/hora, versão e hash do conteúdo) como manifestação de vontade. Este registro não constitui assinatura digital certificada (ICP-Brasil).`;
}
